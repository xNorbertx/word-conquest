import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Engine,configFor} from '../../server/domain.mjs';
import {tilePoints} from '../../online/board-geometry.mjs';
const data={};
for(const language of ['en','sv'])for(const count of [1,2]){
  const config=configFor(language==='sv'?'autumn-sv-v2':'autumn-v4');
  let seed=4287;const random=()=>((seed=Math.imul(seed,1664525)+1013904223>>>0)/4294967296);
  const state=Engine.newGame(config,random);state.player=1;state.startingPlayer=1;state.turns=[6,6];state.lettersUsed=72;
  const own=new Set(['-4,0','-3,0','-3,1','-3,2','-2,2','-2,3','-1,2','-2,1','0,0']);
  const enemy=new Set(['1,-2','2,-2','3,-2','2,-1','3,-1','4,-1','3,0','4,0','0,1','1,1']);
  state.tiles.forEach(t=>{t.owner=own.has(t.id)?1:enemy.has(t.id)?2:0;});
  const solution=language==='sv'?'FÅR':'WORD';
  const path=[...solution].map((letter,i)=>{const id=`${i-2},1`;Object.assign(state.tiles.find(t=>t.id===id),{letter});return id;});
  const jokers=[path[1],...(count===2?[path.at(-1)]:[])];
  jokers.forEach(id=>{state.tiles.find(t=>t.id===id).letter='?';});
  state.wordPoints=[0,0];state.castleIncome=[0,0];
  const base=Engine.scores(state,config);state.wordPoints=[84-base[0],79-base[1]];
  const dictionary=new Set(JSON.parse(fs.readFileSync(new URL(`../../server/versions/dictionary${language==='sv'?'-sv':''}-v1.json`,import.meta.url),'utf8')));
  const words=[];
  function visit(index,letters){
    if(index<jokers.length){for(const letter of config.alphabet||'ABCDEFGHIJKLMNOPQRSTUVWXYZ')visit(index+1,{...letters,[jokers[index]]:letter});return;}
    const word=Engine.wordForPath(state,path,letters);if(dictionary.has(word.toLowerCase()))words.push(word);
  }
  visit(0,{});
  const letters=Object.fromEntries(jokers.map(id=>[id,solution[path.indexOf(id)]]));
  const result=Engine.submit(state,path,config,dictionary,letters,random),score=Engine.scoreMove(state,path,config);
  assert(!result.error,result.error);assert(words.includes(solution));assert.deepEqual(Engine.scores(state,config),[84,79]);
  assert.deepEqual(Engine.scores(result.state,config),[84+score.totalGain,79-score.enemyLoss]);
  data[language+count]={language,solution,path,jokers,words,...score,tiles:state.tiles.map(t=>({...t,value:Engine.letterValue(t.letter,config),points:tilePoints(t)}))};
  console.log(`${language}, ${count} joker(s): ${solution}, ${words.length} valid sample words, +${score.totalGain} points.`);
}
fs.writeFileSync(new URL('./fixture.js',import.meta.url),'// Generated by make-fixture.mjs. Fictional games; current engine and dictionaries.\nwindow.JOKER_DEMO = '+JSON.stringify(data)+';\n');
